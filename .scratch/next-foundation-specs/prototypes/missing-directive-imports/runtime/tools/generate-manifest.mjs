// Writes src/nfs/import-check/manifest.ts: one entry per attribute of every library directive's
// selector. The stand-in directives are read from src/nfs/*.ts; the rest of the library's
// attribute names (tools/spec-attributes.txt, taken from the effort's specs) are added as
// synthetic entries so the manifest has the size of the full library.
// The real library would read the same facts from its compiled partial declarations
// (selector, host classAttribute) after ng-packagr; this regex is enough for the stand-ins.
import { CssSelector } from '@angular/compiler';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const libDir = join(root, 'src/nfs');
const entries = [];

for (const file of readdirSync(libDir).filter((f) => f.endsWith('.ts'))) {
  const source = readFileSync(join(libDir, file), 'utf8');
  const decorator = /@Directive\(\{\s*selector:\s*'([^']+)',\s*host:\s*\{([^}]*)\}[\s\S]*?export class (\w+)/g;

  for (const [, selector, host, directive] of source.matchAll(decorator)) {
    const hostClass = /\bclass:\s*'([^']+)'/.exec(host)?.[1] ?? null;
    const attributes = new Set();

    for (const parsed of CssSelector.parse(selector)) {
      for (let i = 0; i < parsed.attrs.length; i += 2) {
        attributes.add(parsed.attrs[i]);
      }
    }

    for (const attribute of attributes) {
      entries.push({
        directive,
        entryPoint: `ngx-foundation-sites/${file.replace(/\.ts$/, '')}`,
        selector,
        attribute,
        hostClass,
      });
    }
  }
}

const known = new Set(entries.map((e) => e.attribute));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/^-/, '');

for (const attribute of readFileSync(join(root, 'tools/spec-attributes.txt'), 'utf8').split(/\r?\n/)) {
  if (!attribute || known.has(attribute)) {
    continue;
  }

  const name = attribute.slice(3);
  entries.push({
    directive: `Nfs${name}`,
    entryPoint: `ngx-foundation-sites/${kebab(name)}`,
    selector: `[${attribute}]`,
    attribute,
    hostClass: kebab(name),
  });
}

const out =
  `// Generated by tools/generate-manifest.mjs; do not edit.\n` +
  `import { NfsImportManifestEntry } from './types';\n\n` +
  `export const nfsImportManifest: readonly NfsImportManifestEntry[] = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(join(libDir, 'import-check/manifest.ts'), out);
console.log(`${entries.length} entries, ${known.size} from stand-ins`);
