// Q1: after the Variant declaration file changes during `ng serve` / `nx serve`, which rewrites
// reach the template diagnostics? Usage (from anywhere):
//   node q1-dev-server.cjs <cli|nx> <variant> <port>
// variants: baseline, reference (/// <reference path> from main.ts), files (tsconfig files entry),
//           global (the file carries an empty `declare global {}`), touch (edit the component after each rewrite),
//           tool (cli only: edit the Sass, then `ng run cli-ws:nfs-variants` rewrites the file)
const fs = require('node:fs');
const path = require('node:path');
const { spawn, execSync } = require('node:child_process');

const [kind, variant, port] = process.argv.slice(2);
const ws = path.resolve(__dirname, kind === 'cli' ? '../cli-ws' : '../nx-ws');
const src = kind === 'cli' ? 'src' : 'apps/shop/src';
const tsconfigApp =
  kind === 'cli' ? 'tsconfig.app.json' : 'apps/shop/tsconfig.app.json';
const declFile = path.join(ws, src, 'nfs-variants.d.ts');
const mainFile = path.join(ws, src, 'main.ts');
const appFile = path.join(ws, src, 'app/app.ts');
const tsconfigFile = path.join(ws, tsconfigApp);
const logFile = path.resolve(
  __dirname,
  `../logs/q1-${kind}-${variant}${process.env.SPEND_FIRST ? '-spent' : ''}.log`,
);
const settingsFile = path.join(ws, src, '_app-settings.scss');
const originals = new Map(
  [declFile, mainFile, appFile, tsconfigFile, settingsFile].map((f) => [
    f,
    fs.readFileSync(f, 'utf8'),
  ]),
);
const project = kind === 'cli' ? 'cli-ws' : 'shop';
const header = `// Generated by ngx-foundation-sites from ${src}/styles.scss. Do not edit; run ${kind === 'cli' ? '`ng run cli-ws:nfs-variants`' : '`nx sync` or `nx run shop:nfs-variants`'} to update it.\nimport 'ngx-foundation-sites';\n\n`;
const globalBlock = variant === 'global' ? 'declare global {}\n\n' : '';
const inStep = originals.get(declFile).includes('purple: true');
const withPurple = `${header}${globalBlock}declare module 'ngx-foundation-sites' {\n  interface NfsButtonPaletteOverrides {\n    purple: true;\n  }\n}\n`;
const withoutPurple = `${header}${globalBlock}declare module 'ngx-foundation-sites' {}\n`;

if (!inStep) {
  throw new Error('start from a declaration file that declares purple');
}

function applyVariant() {
  if (variant === 'upgrade') {
    fs.writeFileSync(
      declFile,
      fs.readFileSync(
        path.resolve(__dirname, '../logs/cli-nfs-variants-old.d.ts.txt'),
        'utf8',
      ),
    );
  }

  if (variant === 'global') {
    fs.writeFileSync(declFile, withPurple);
  }

  if (variant === 'reference') {
    fs.writeFileSync(
      mainFile,
      `/// <reference path="./nfs-variants.d.ts" />\n${originals.get(mainFile)}`,
    );
  }

  if (variant === 'files') {
    // Drop only the whole-line header comments: a block-comment regex would eat "src/**/*.ts".
    const json = JSON.parse(
      originals
        .get(tsconfigFile)
        .split('\n')
        .filter((l) => !l.trim().startsWith('/*'))
        .join('\n'),
    );
    json.files = [...(json.files ?? []), 'src/nfs-variants.d.ts'];
    fs.writeFileSync(tsconfigFile, JSON.stringify(json, null, 2) + '\n');
  }
}

function restore() {
  for (const [f, text] of originals) {
    fs.writeFileSync(f, text);
  }
}

let log = '';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const done = () =>
  (log.match(/Application bundle generation (complete|failed)/g) ?? []).length;

async function waitForRebuild(before, timeoutMs = 30000) {
  const start = Date.now();

  while (done() <= before && Date.now() - start < timeoutMs) {
    await sleep(100);
  }

  await sleep(1500);

  return done() > before;
}

(async () => {
  applyVariant();
  const cmd =
    kind === 'cli'
      ? `npx ng serve --port ${port}`
      : `npx nx serve shop --port ${port} --skip-sync`;
  const child = spawn(cmd, {
    cwd: ws,
    shell: true,
    env: {
      ...process.env,
      NFS_TRACE: '1',
      NX_DAEMON: 'false',
      NG_CLI_ANALYTICS: 'false',
      FORCE_COLOR: '0',
    },
  });
  child.stdout.on('data', (d) => (log += d));
  child.stderr.on('data', (d) => (log += d));
  const steps = [];

  try {
    await waitForRebuild(0, 180000);
    steps.push({
      step: 'initial build (file declares purple)',
      purpleError: /TS2322[^\n]*"purple"/.test(log),
      rebuilt: true,
    });

    if (variant === 'upgrade' || process.env.SPEND_FIRST) {
      // Spend the first incremental rebuild on a component edit, so the next rewrite cannot
      // profit from the placeholder type-check shim.
      const b = done();
      const mark = log.length;
      fs.writeFileSync(appFile, `${fs.readFileSync(appFile, 'utf8')}\n`);
      const rebuilt = await waitForRebuild(b);
      steps.push({
        step: 'component edit (spends the first rebuild)',
        rebuilt,
        trace: log
          .slice(mark)
          .split('\n')
          .filter((l) => l.includes('ttc shim affected app'))
          .map((l) => l.trim()),
      });
    }

    const rounds = [
      ['rewrite 1: purple removed', withoutPurple],
      ['rewrite 2: purple back', withPurple],
      ['rewrite 3: purple removed', withoutPurple],
      ['rewrite 4: purple back', withPurple],
      ['rewrite 5: purple removed', withoutPurple],
    ];

    for (const [label, text] of rounds) {
      const before = done();
      const mark = log.length;
      if (variant === 'tool' || variant === 'upgrade') {
        const settings = originals.get(settingsFile);
        fs.writeFileSync(
          settingsFile,
          text === withoutPurple
            ? settings.replace(', (purple: #7a3fbf)', ', ()')
            : settings,
        );
        execSync(
          kind === 'cli' ? `npx ng run ${project}:nfs-variants` : 'npx nx sync',
          {
            cwd: ws,
            stdio: 'ignore',
            env: { ...process.env, NX_DAEMON: 'false' },
          },
        );
      } else {
        fs.writeFileSync(declFile, text);
      }
      let rebuilt = await waitForRebuild(before);

      if (variant === 'touch') {
        const b2 = done();
        fs.writeFileSync(appFile, `${fs.readFileSync(appFile, 'utf8')}\n`);
        rebuilt = (await waitForRebuild(b2)) || rebuilt;
      }

      const chunk = log.slice(mark);
      const expected = text === withoutPurple;
      // Judge the last rebuild only: a Sass edit adds a rebuild of its own before the rewrite.
      const lastRebuild = chunk.slice(
        chunk.lastIndexOf('Application bundle generation'),
      );
      const purpleError = /TS2322[^\n]*"purple"/.test(lastRebuild);
      const rebuilds = (
        chunk.match(/Application bundle generation (complete|failed)/g) ?? []
      ).length;
      steps.push({
        step: label,
        rebuilt,
        rebuilds,
        purpleError,
        correct: purpleError === expected,
        trace: chunk
          .split('\n')
          .filter((l) => l.includes('[nfs-trace]'))
          .map((l) => l.trim()),
      });
    }
  } finally {
    try {
      execSync(`taskkill /PID ${child.pid} /T /F`, { stdio: 'ignore' });
    } catch {
      // already gone
    }

    restore();
    fs.writeFileSync(logFile, log.replace(/\x1b\[[0-9;]*m/g, ''));
  }

  const summary = { kind, variant, steps };
  fs.writeFileSync(
    logFile.replace(/\.log$/, '.json'),
    JSON.stringify(summary, null, 2) + '\n',
  );

  for (const s of steps) {
    console.log(
      `${s.step}: rebuilt=${s.rebuilt} rebuilds=${s.rebuilds ?? 1} TS2322-on-purple=${s.purpleError}${s.correct === undefined ? '' : ` correct=${s.correct}`}`,
    );

    for (const t of s.trace ?? []) {
      console.log(`    ${t}`);
    }
  }
})();
