/** Angular's merge: base options, then each named configuration's. */
function mergeTargetOptions(target, configuration) {
  const name = configuration ?? target.defaultConfiguration;
  let options = { ...(target.options ?? {}) };

  for (const c of (name ?? '')
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)) {
    options = { ...options, ...(target.configurations?.[c] ?? {}) };
  }

  return { options, configuration: name ?? null };
}

/**
 * Warning M11: configurations of the build target that change the styles. The used
 * configuration counts too: when it overrides styles, every other configuration (the
 * dev server's development configuration, say) builds with different ones.
 */
function styleOverrideWarnings(target, used, buildTarget, file) {
  const warnings = [];

  for (const [name, config] of Object.entries(target.configurations ?? {})) {
    if (
      config &&
      ('styles' in config || 'stylePreprocessorOptions' in config)
    ) {
      warnings.push(
        `${PREFIX} the ${name} configuration of ${buildTarget} changes styles or stylePreprocessorOptions; ${file} follows ${used ? `the ${used} configuration` : 'the base options'}.`,
      );
    }
  }

  return warnings;
}

/** Sources from merged build options: every injected Sass global stylesheet. */
function sourcesFromBuildOptions(options) {
  const styles = (options.styles ?? []).map((s) =>
    typeof s === 'string'
      ? { input: s, inject: true }
      : { input: s.input, inject: s.inject !== false },
  );
  const optimization = options.optimization;
  const optimized =
    optimization === undefined
      ? true
      : typeof optimization === 'object'
        ? !!(typeof optimization.styles === 'object'
            ? (optimization.styles.minify ?? true)
            : (optimization.styles ?? false))
        : !!optimization;

  return {
    stylesheets: styles
      .filter((s) => s.inject && /\.s[ac]ss$/.test(s.input))
      .map((s) => posix(s.input)),
    includePaths: options.stylePreprocessorOptions?.includePaths ?? [],
    optimized,
  };
}

