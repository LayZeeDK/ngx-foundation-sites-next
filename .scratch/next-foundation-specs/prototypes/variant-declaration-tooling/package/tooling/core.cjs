const PREFIX = 'ngx-foundation-sites:';
const MODULE = 'ngx-foundation-sites';
const FILE_NAME = 'nfs-variants.d.ts';
const HEADER_START = '// Generated by ngx-foundation-sites';
const manifest = require('./manifest.json');
const libraryVersion = require('../package.json').version;
const bySetting = new Map(manifest.registries.map((r) => [r.setting, r]));
const byName = new Map(manifest.registries.map((r) => [r.registry, r]));

function load(name, fromDirs, who) {
  for (const dir of fromDirs) {
    try {
      return require(require.resolve(name, { paths: [dir] }));
    } catch {
      // try the next location
    }
  }

  throw new Error(
    `${PREFIX} the ${who} needs ${name}. Install it: npm install --save-dev ${name}`,
  );
}

function angularBuildDir(root) {
  try {
    return path.dirname(
      require.resolve('@angular/build/package.json', { paths: [root] }),
    );
  } catch {
    return null;
  }
}

const posix = (p) => p.replace(/\\/g, '/');

