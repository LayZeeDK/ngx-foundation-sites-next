const key = (n) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(n) ? n : `'${n}'`);

function command(workspaceKind, project) {
  return workspaceKind === 'nx'
    ? `\`nx sync\` or \`nx run ${project}:nfs-variants\``
    : `\`ng run ${project}:nfs-variants\``;
}

function render(expected, sources, workspaceKind, project) {
  const names = [...expected.keys()].sort();
  const blocks = names.map((name) => {
    const entry = expected.get(name);
    const members =
      entry.count !== undefined
        ? [`    count: ${entry.count};`]
        : [
            ...entry.adds.map((n) => `    ${key(n)}: true;`),
            ...entry.removes.map((n) => `    ${key(n)}: false;`),
          ];

    return `  interface ${name} {\n${members.join('\n')}\n  }`;
  });
  const body = blocks.length
    ? `declare module '${MODULE}' {\n${blocks.join('\n')}\n}`
    : `declare module '${MODULE}' {}`;

  // The empty global augmentation makes TypeScript's builder treat a change to this file as
  // affecting every file (isFileAffectingGlobalScope), so a running dev server re-checks
  // every template after each rewrite (ticket 137, question 1).
  return [
    `${HEADER_START} from ${sources.join(', ')}. Do not edit; run ${command(workspaceKind, project)} to update it.`,
    `import '${MODULE}';`,
    '',
    body,
    '',
    '// Makes a running dev server re-check templates after every change to this file.',
    'declare global {}',
    '',
  ].join('\n');
}

async function format(text, absoluteFile, root) {
  let prettier;

  try {
    prettier = require(require.resolve('prettier', { paths: [root] }));
  } catch {
    return text;
  }

  const info = await prettier.getFileInfo(absoluteFile, {
    ignorePath: path.join(root, '.prettierignore'),
  });

  if (info.ignored) {
    return text;
  }

  const config = (await prettier.resolveConfig(absoluteFile)) ?? {};

  return prettier.format(text, { ...config, filepath: absoluteFile });
}

// ---------------------------------------------------------------------------
// One project, end to end. readFile(workspaceRelativePath) returns text or null.
// ---------------------------------------------------------------------------

async function processProject({
  root,
  project,
  workspaceKind,
  file,
  sources,
  readFile,
  warnings = [],
}) {
  const ts = load('typescript', [root], 'Variant declaration tooling');
  const compiled = await compileSources(root, sources, project);
  const found = readProperties(compiled, project);
  const expected = expectedModel(found);
  const sourceList = compiled.map((c) => c.stylesheet);
  const current = readFile(file);
  const timing = compiled
    .map((c) => `${c.stylesheet} ${c.ms} ms, ${c.loadedUrls} files`)
    .join('; ');
  const properties = Object.fromEntries(
    [...found].map(([p, v]) => [p, v.value.raw]),
  );

  if (current === null) {
    const content = await format(
      render(expected, sourceList, workspaceKind, project),
      path.join(root, file),
      root,
    );

    return {
      status: 'write',
      file,
      content,
      drift: [{ registry: '(file)', lines: ['the file does not exist'] }],
      sourceList,
      timing,
      properties,
      warnings,
    };
  }

  const model = parseDeclarationFile(current, file, ts);

  if (model.problems.length) {
    return {
      status: 'problem',
      file,
      problems: model.problems,
      sourceList,
      timing,
      properties,
      warnings,
    };
  }

  const { drift, open } = compare(expected, model, found);

  if (!drift.length) {
    return {
      status: 'in-step',
      file,
      drift,
      open,
      sourceList,
      timing,
      properties,
      warnings,
    };
  }

  if (!model.generated) {
    return {
      status: 'hand-written-drift',
      file,
      drift,
      sourceList,
      timing,
      properties,
      warnings,
    };
  }

  const content = await format(
    render(expected, sourceList, workspaceKind, project),
    path.join(root, file),
    root,
  );

  return {
    status: 'write',
    file,
    content,
    drift,
    sourceList,
    timing,
    properties,
    warnings,
  };
}

function driftSummary(drift) {
  return drift.map((d) => `${d.registry}: ${d.lines.join('; ')}`).join('; ');
}

/** M2 (check failure), M4 (hand-written drift), M5 to M7 (problems). */
function failureMessage(result, workspaceKind, project) {
  if (result.status === 'problem') {
    return result.problems.map((p) => `${PREFIX} ${p.text}`).join('\n');
  }

  const lines = result.drift.flatMap((d) =>
    d.lines.map((l) => `  ${d.registry}: ${l}`),
  );

  if (result.status === 'hand-written-drift') {
    return [
      `${PREFIX} ${result.file} was not generated by ngx-foundation-sites, so it is not rewritten. Make these edits:`,
      ...lines,
      'or delete it to let the tooling write it.',
    ].join('\n');
  }

  return [
    `${PREFIX} ${result.file} no longer matches ${result.sourceList.join(', ')}:`,
    ...lines,
    `Run ${command(workspaceKind, project)} to update it.`,
  ].join('\n');
}

