// PROTOTYPE (ticket 190 option S): writes `app/<page>.static.ts` from each scenario page, with the
// shared directives import split into per-family modules, so each page's families land in that
// page's chunk graph. build-all.sh runs this before the `build-static` target.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const app = join(import.meta.dirname, '..', 'apps', 'fixture', 'src', 'app');
const modules = {
  NfsButton: 'button',
  NfsCallout: 'callout',
  NfsMenu: 'menu',
  NfsDropdownMenu: 'dropdown-menu',
  NfsDropdownPane: 'dropdown',
};

for (const page of ['landing-page', 'menus-page', 'defer-page']) {
  const source = readFileSync(join(app, `${page}.ts`), 'utf8');
  const match = /import \{([^}]+)\} from '\.\.\/lib\/directives';\n/.exec(source);

  if (!match) {
    throw new Error(`${page}: no directives import`);
  }

  const imports = match[1]
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((name) => `import { ${name} } from '../lib/directives/${modules[name]}.static';\n`)
    .join('');
  const header = `// GENERATED by tools/gen-static-pages.mjs from ${page}.ts for option S. Do not edit.\n`;
  writeFileSync(join(app, `${page}.static.ts`), header + source.replace(match[0], imports));
}
